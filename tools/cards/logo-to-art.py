"""Turns the Blatero Studio logo into the BLATERO card's pixel art (tools/cards/art/blatero.mjs).
Usage: python3 tools/cards/logo-to-art.py [crop_top crop_bottom threshold]"""
import sys
from PIL import Image

W, H = 64, 48
top, bottom, thr = (int(a) for a in (sys.argv[1:4] if len(sys.argv) > 3 else (0, 760, 120)))
im = Image.open('tools/cards/ref/blatero-studio-logo.png').convert('L')
crop = im.crop((0, top, im.width, bottom))
h = H
w = round(crop.width * h / crop.height)
small = crop.resize((w, h), Image.LANCZOS)
x0 = (W - w) // 2
rows = []
for y in range(H):
    row = ''
    for x in range(W):
        sx = x - x0
        row += '#' if 0 <= sx < w and small.getpixel((sx, y)) > thr else '.'
    rows.append(row)
# The eye is the logo's signature: redraw it crisply over the downscale.
EYE_X, EYE_Y, EYE_R = 355, 322, 66  # in the source image
k = h / crop.height
ex, ey, er = x0 + EYE_X * k, (EYE_Y - top) * k, EYE_R * k
for y in range(H):
    r = list(rows[y])
    for x in range(W):
        d = ((x + 0.5 - ex) ** 2 + (y + 0.5 - ey) ** 2) ** 0.5
        if d <= er + 1.2:
            if d > er: r[x] = '.'            # dark outline
            elif d > er * 0.62: r[x] = '#'   # white of the eye
            elif d > er * 0.2: r[x] = '.'    # dark iris
            else: r[x] = '.'
    rows[y] = ''.join(r)
# catch-light
hx, hy = int(ex - er * 0.3), int(ey - er * 0.3)
rows[hy] = rows[hy][:hx] + '#' + rows[hy][hx + 1:]
body = ',\n'.join(f"    '{r}'" for r in rows)
open('tools/cards/art/blatero.mjs', 'w').write(f"""// BLATERO Studio logo in 1-bit pixel art (generated by tools/cards/logo-to-art.py from tools/cards/ref/blatero-studio-logo.png).
export const size = [{W}, {H}]
const ROWS = [
{body},
]
export default function draw({{ rect }}) {{
  rect(0, 0, {W}, {H}, 0)
  ROWS.forEach((row, y) => [...row].forEach((c, x) => c === '#' && rect(x, y, 1, 1, 7)))
}}
""")
print('wrote', w, 'x', h)
