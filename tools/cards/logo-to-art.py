"""Turns the Blatero Studio logo into the BLATERO card's pixel art (tools/cards/art/blatero.mjs).
Usage: python3 tools/cards/logo-to-art.py
Crops the portrait to head and shoulders, downsamples with box averaging so the logo's dithered
greys survive, and posterises to four greys of the PICO-8 palette (0 black, 5 dark grey,
6 light grey, 7 white). The eye, the logo's signature, is redrawn crisply on top."""
from PIL import Image

W, H = 64, 48
SRC = 'tools/cards/ref/blatero-studio-logo.png'
CROP = (30, 16, 550, 610)        # left, top, right, bottom in the source: hair to shoulders
LEVELS = [(60, 0), (120, 5), (175, 6), (256, 7)]  # grey value below the bound maps to the colour
EYE_X, EYE_Y, EYE_R = 352, 324, 64  # eye centre and radius in the source

im = Image.open(SRC).convert('L')
crop = im.crop(CROP)
w = round(crop.width * H / crop.height)
small = crop.resize((w, H), Image.BOX)
x0 = (W - w) // 2
grid = [[0] * W for _ in range(H)]
for y in range(H):
    for x in range(w):
        v = small.getpixel((x, y))
        grid[y][x0 + x] = next(c for bound, c in LEVELS if v < bound)

# Clean up speckle: a lone pixel whose four neighbours mostly agree takes their colour.
for y in range(1, H - 1):
    for x in range(1, W - 1):
        n = [grid[y - 1][x], grid[y + 1][x], grid[y][x - 1], grid[y][x + 1]]
        if grid[y][x] not in n:
            top = max(set(n), key=n.count)
            if n.count(top) >= 3: grid[y][x] = top

# Eye: dark outline, white of the eye, dark grey iris ring, black pupil, catch-light.
k = H / crop.height
ex, ey, er = x0 + (EYE_X - CROP[0]) * k, (EYE_Y - CROP[1]) * k, EYE_R * k * 1.1  # a touch bigger: it is the focal point
for y in range(H):
    for x in range(W):
        d = ((x + 0.5 - ex) ** 2 + (y + 0.5 - ey) ** 2) ** 0.5
        if d <= er + 1.0:
            grid[y][x] = 0 if d > er else 7 if d > er * 0.6 else 5 if d > er * 0.38 else 0
grid[int(ey - er * 0.22)][int(ex - er * 0.2)] = 7
grid[int(ey - er * 0.22)][int(ex - er * 0.2) + 1] = 6

HEX = '0123456789abcdef'
body = ',\n'.join("    '" + ''.join('.' if c == 0 else HEX[c] for c in row) + "'" for row in grid)
open('tools/cards/art/blatero.mjs', 'w').write(f"""// BLATERO Studio logo as pixel art in four greys (generated by tools/cards/logo-to-art.py from tools/cards/ref/blatero-studio-logo.png).
export const size = [{W}, {H}]
const ROWS = [
{body},
]
export default function draw({{ rect }}) {{
  rect(0, 0, {W}, {H}, 0)
  ROWS.forEach((row, y) => [...row].forEach((c, x) => c !== '.' && rect(x, y, 1, 1, parseInt(c, 16))))
}}
""")
print('wrote', w, 'x', H)
